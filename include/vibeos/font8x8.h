/* One row of one glyph: eight pixels, least significant bit leftmost. Null for
 * a character the font does not cover, or a row past the glyph. */
static inline const uint8_t *vibeos_font8x8_row(char c, uint32_t row) {
    if (row >= VIBEOS_FONT8X8_HEIGHT) {
        return 0;
    }
    if ((unsigned char)c < 0x20u || (unsigned char)c > 0x7Eu) {
        return 0;
    }
    return &vibeos_font8x8[(unsigned char)c - 0x20u][row];
}

