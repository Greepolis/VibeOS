"""docs/open-items.md: every item still open, gathered from the registers.

    make-open-items.py          write docs/open-items.md
    make-open-items.py --check  fail if docs/open-items.md is not what it would write

The registers stay where they are and stay the record: an item is opened,
argued and closed in its own register's row. This file only gathers the rows
whose status says open, so that what is left can be read in one place beside
docs/next-steps.md. It is generated rather than kept by hand because a list
copied from the registers drifts from them - the progress table and its detail
files contradicted each other twice (CLAUDE.md, "Everything gets tracked in the
docs") - and --check runs in static-checks.sh so a register changed without
re-running this is red.

A register is any table under docs/ whose header has an "ID" column and a
"Status" column; a row is open when its status cell starts with "open".
"""

import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DOCS = os.path.join(ROOT, "docs")
OUT = os.path.join(DOCS, "open-items.md")
ID = re.compile(r"^[A-Z][A-Z0-9]*-\d+$")
WHAT = ("what", "finding", "item", "gap", "description")


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def short(text, n=160):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= n else text[:n].rsplit(" ", 1)[0] + " ..."


def scan(path):
    """(title, [(id, what, status)]) for one markdown file."""
    rows, title = [], None
    header = None
    with open(path, encoding="utf-8") as f:
        lines = f.read().splitlines()
    for line in lines:
        if title is None and line.startswith("# "):
            title = line[2:].strip()
        if not line.startswith("|"):
            header = None
            continue
        c = cells(line)
        low = [x.lower() for x in c]
        if "id" in low and "status" in low:
            header = (low.index("id"), low.index("status"),
                      next((low.index(w) for w in WHAT if w in low), None))
            continue
        if header is None or set(line.replace("|", "").strip()) <= set("-: "):
            continue
        i_id, i_st, i_what = header
        if len(c) <= max(i_id, i_st) or not ID.match(c[i_id]):
            continue
        status = c[i_st].replace("*", "").strip()
        if not status.lower().startswith("open"):
            continue
        what = c[i_what] if i_what is not None and i_what < len(c) else ""
        rows.append((c[i_id], short(what), short(status, 80)))
    return title or os.path.basename(path), rows


def render():
    found = []
    for d, _, files in os.walk(DOCS):
        for name in sorted(files):
            p = os.path.join(d, name)
            if not name.endswith(".md") or p == OUT:
                continue
            title, rows = scan(p)
            if rows:
                found.append((os.path.relpath(p, DOCS).replace(os.sep, "/"), title, rows))
    found.sort()
    total = sum(len(r) for _, _, r in found)
    out = ["# Open items", "",
           "Everything still open, gathered from the registers - generated by",
           "`scripts/dev/make-open-items.py`; do not edit it. An item is opened, argued",
           "and closed in its own register, whose row is the record; re-run the script",
           "after changing one (`static-checks.sh` fails until you do). The order of work",
           "is [next-steps.md](next-steps.md).", "",
           "%d open in %d registers." % (total, len(found)), ""]
    for rel, title, rows in found:
        out += ["## [%s](%s) - %d" % (title, rel, len(rows)), "", "| ID | What | Status |", "|---|---|---|"]
        for i, what, status in rows:
            out.append("| %s | %s | %s |" % (i, what.replace("|", "\\|"), status.replace("|", "\\|")))
        out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = ""
        if have != text:
            print("open-items=FAIL docs/open-items.md is stale: run scripts/dev/make-open-items.py")
            return 1
        print("open-items=ok")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("open-items written: %s" % text.splitlines()[8])
    return 0


if __name__ == "__main__":
    sys.exit(main())
