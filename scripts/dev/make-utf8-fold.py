"""Generate kernel/fs/utf8fold_data.h from the Unicode 12.1 character database
(E4-030).

    scripts/dev/make-utf8-fold.py <ucd-12.1-dir> [out]

ext4's casefolded directories compare names as Linux's utf8-12.1 does: each
name taken to "nfdicf" - full case folding (CaseFolding.txt status C and F)
and then canonical decomposition, recursively, with combining marks put in
canonical order - and compared byte for byte. A code point not assigned in
12.1 makes the name invalid, and a non-strict volume then compares it as
bytes. The tables are generated from the 12.1 files rather than from Python's
own unicodedata, which is a later version and would fold characters Linux
calls unassigned.

What this writes, all sorted for binary search:
  - the assigned ranges of 12.1;
  - each code point whose nfdicf differs from itself, with its expansion;
  - each code point with a non-zero canonical combining class.
Hangul syllables are decomposed by the algorithm, not listed.

The input files are not in the repository; their digests are written into the
header, so a regeneration from different data shows in the diff.
"""
import hashlib
import os
import sys

HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    d = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(__file__), "..", "..", "kernel", "fs", "utf8fold_data.h")
    ud_path, cf_path = os.path.join(d, "UnicodeData.txt"), os.path.join(d, "CaseFolding.txt")
    if "12.1.0" not in open(cf_path, encoding="utf-8").readline():
        print("CaseFolding.txt is not 12.1.0")
        return 1

    assigned, decomp, ccc = [], {}, {}
    first = None
    for line in open(ud_path, encoding="utf-8"):
        f = line.rstrip("\n").split(";")
        cp, name = int(f[0], 16), f[1]
        if name.endswith(", First>"):
            first = cp
            continue
        lo = first if name.endswith(", Last>") else cp
        first = None
        assigned.append((lo, cp))
        if int(f[3]):
            ccc[cp] = int(f[3])
        if f[5] and not f[5].startswith("<"):   # canonical only: <tag> is compatibility
            decomp[cp] = [int(x, 16) for x in f[5].split()]

    fold = {}
    for line in open(cf_path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(";")]
        if f[1] in ("C", "F"):
            fold[int(f[0], 16)] = [int(x, 16) for x in f[2].split()]

    def nfd(cp):
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            return [cp]   # the runtime decomposes these
        if cp in decomp:
            return [y for x in decomp[cp] for y in nfd(x)]
        return [cp]

    def nfdicf(cp):
        return [y for x in fold.get(cp, [cp]) for y in nfd(x)]

    # Merge adjacent ranges.
    assigned.sort()
    ranges = []
    for lo, hi in assigned:
        if ranges and lo <= ranges[-1][1] + 1:
            ranges[-1][1] = max(ranges[-1][1], hi)
        else:
            ranges.append([lo, hi])

    maps, pool = [], []
    for cp in sorted(set(decomp) | set(fold)):
        x = nfdicf(cp)
        if x != [cp]:
            maps.append((cp, len(pool), len(x)))
            pool += x
    maxlen = max(n for _, _, n in maps)

    dig = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
    o = []
    o.append("/* SPDX-License-Identifier: GPL-3.0-or-later */")
    o.append("/* Generated by scripts/dev/make-utf8-fold.py from the Unicode 12.1.0")
    o.append(" * character database - do not edit. (E4-030)")
    o.append(" *   UnicodeData.txt sha256 %s" % dig(ud_path))
    o.append(" *   CaseFolding.txt sha256 %s */" % dig(cf_path))
    o.append("#ifndef VIBEOS_FS_UTF8FOLD_DATA_H")
    o.append("#define VIBEOS_FS_UTF8FOLD_DATA_H")
    o.append("")
    o.append("#define UTF8FOLD_MAX_EXPANSION %du" % maxlen)
    o.append("")
    o.append("static const uint32_t g_u8f_assigned[][2] = {")
    o += ["    {0x%X, 0x%X}," % (a, b) for a, b in ranges]
    o.append("};")
    o.append("")
    o.append("/* code point, first of its expansion in g_u8f_pool, length */")
    o.append("static const uint32_t g_u8f_map[][3] = {")
    o += ["    {0x%X, %d, %d}," % m for m in maps]
    o.append("};")
    o.append("")
    o.append("static const uint32_t g_u8f_pool[] = {")
    for i in range(0, len(pool), 8):
        o.append("    " + " ".join("0x%X," % x for x in pool[i:i + 8]))
    o.append("};")
    o.append("")
    o.append("/* code point, canonical combining class */")
    o.append("static const uint32_t g_u8f_ccc[][2] = {")
    o += ["    {0x%X, %d}," % (cp, ccc[cp]) for cp in sorted(ccc)]
    o.append("};")
    o.append("")
    o.append("#endif")
    open(out, "w", newline="\n").write("\n".join(o) + "\n")
    print("utf8fold: ranges=%d maps=%d pool=%d ccc=%d max_expansion=%d" %
          (len(ranges), len(maps), len(pool), len(ccc), maxlen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
